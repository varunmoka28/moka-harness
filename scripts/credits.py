#!/usr/bin/env python3
"""Write CREDITS.md from .claude-plugin/marketplace.json (third-party entries only).

Usage: credits.py [--root DIR] [--date YYYY-MM-DD]
The date defaults to today and is the 'date checked' column. A row whose pin is
unchanged since the last CREDITS.md keeps its old date; only new or re-pinned rows get --date.
"""
import argparse, datetime, json, os, re, sys


def repo_link(src):
    ref = src.get("repo") or src.get("url") or ""
    m = re.match(r"^(?:https?://github\.com/)?([\w.-]+/[\w.-]+?)(?:\.git)?/?$", ref)
    if m:
        return f"https://github.com/{m.group(1)}"
    return ref


def cell(s):
    return str(s or "unknown").replace("|", "\\|").replace("\n", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap.add_argument("--date", default=datetime.date.today().isoformat())
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    market = json.load(open(os.path.join(root, ".claude-plugin", "marketplace.json")))
    out = os.path.join(root, "CREDITS.md")
    checked = {}  # name -> (sha cell, date) from the last CREDITS.md
    if os.path.exists(out):
        for line in open(out):
            c = [x.strip() for x in line.split("|")]
            if len(c) == 8 and c[5].startswith("`"):
                checked[c[1]] = (c[5], c[6])
    rows = []
    for p in market.get("plugins", []):
        src = p.get("source")
        if not isinstance(src, dict):
            continue
        author = p.get("author")
        author = author.get("name") if isinstance(author, dict) else author
        sha = "`" + cell(src.get("sha")) + "`"
        old = checked.get(cell(p["name"]))
        date = old[1] if old and old[0] == sha else a.date
        rows.append("| " + " | ".join([
            cell(p["name"]), cell(author), cell(repo_link(src)), cell(p.get("license")), sha, date]) + " |")
    text = ("# Credits\n\n"
            "Generated by scripts/credits.py from .claude-plugin/marketplace.json. Do not edit by hand.\n\n"
            "| Entry | Author | Repo | Licence | Pinned commit | Date checked |\n"
            "|---|---|---|---|---|---|\n" + "\n".join(rows) + ("\n" if rows else ""))
    open(out, "w").write(text)


if __name__ == "__main__":
    sys.exit(main())
